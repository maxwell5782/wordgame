export const WORDS = Object.entries(RAW).flatMap(([topic, list]) =>
  list.map(([en, zh, emoji, level]) => ({ en, zh, emoji, level, topic })));

export const TOPICS = Object.keys(RAW);
export const ALL_TOPICS = '全部';

export const LEVELS = { 1: '入門', 2: '基礎', 3: '進階' };
export const ALL_LEVELS = 0;

// topic 為 ALL_TOPICS、level 為 ALL_LEVELS（或沒給）時不篩選
export function wordsForTopic(topic, level = ALL_LEVELS) {
  return WORDS.filter(w =>
    (!topic || topic === ALL_TOPICS || w.topic === topic) && (!level || w.level === level));
}

export function findWord(en) {
  return WORDS.find(w => w.en === en);
}
